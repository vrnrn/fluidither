// --- Rust ------------------------------------------------------------------

const float = (value) => {
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
};

// A struct literal, because gpui's rgba() is not a const fn.
const rgba = (hex) => {
  const { r, g, b, a } = parseHex(hex);
  const channel = (value) => float(Number((value / 255).toFixed(6)));
  return `Rgba { r: ${channel(r)}, g: ${channel(g)}, b: ${channel(b)}, a: ${channel(a)} }`;
};

const themeFields = [...Object.keys(tokens.themes.light).map(snake), ...Object.keys(tokens.palette.hues)];

const rustTheme = (theme, name) => `pub const ${name}: ThemeColors = ThemeColors {
${Object.entries(tokens.themes[theme])
  .map(([key, value]) => `    ${snake(key)}: ${rgba(value)},`)
  .join('\n')}
${palette(theme)
  .map(([key, value]) => `    ${key}: ${rgba(value)},`)
  .join('\n')}
    surfaces: [${tokens.surfaces[theme].map(rgba).join(', ')}],
};`;

const rustSize = (name, size) => `pub const ${name}: SizeTokens = SizeTokens {
${Object.entries(size)
  .map(([key, value]) => `    ${snake(key)}: ${float(value)},`)
  .join('\n')}
};`;

