const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

// --- Springs ---------------------------------------------------------------

// Tokens say how long a spring takes and how damped it is. The physics needs a
// frequency: the one whose step response has come within 0.1% by `duration`.
function frequency({ duration, damping }) {
  const within = 0.001;
  const remaining = (omega) => {
    if (damping >= 1) return Math.exp(-omega * duration) * (1 + omega * duration);
    return Math.exp(-damping * omega * duration) / Math.sqrt(1 - damping * damping);
  };
  let low = 0;
  let high = 4096;
  for (let step = 0; step < 80; step += 1) {
    const middle = (low + high) / 2;
    if (remaining(middle) > within) low = middle;
    else high = middle;
  }
  return high;
}

function stepResponse({ omega, damping }, t) {
  if (damping >= 1) return 1 - Math.exp(-omega * t) * (1 + omega * t);
  const ringing = omega * Math.sqrt(1 - damping * damping);
  const envelope = Math.exp(-damping * omega * t);
  return 1 - envelope * (Math.cos(ringing * t) + ((damping * omega) / ringing) * Math.sin(ringing * t));
}

// The same curve as a CSS easing, so a plain transition lands like a spring.
function cssEasing(spring) {
  const samples = 20;
  const stops = Array.from({ length: samples + 1 }, (_, i) =>
    Number(stepResponse(spring, (spring.duration * i) / samples).toFixed(3)),
  );
  stops[samples] = 1;
  return `linear(${stops.join(', ')})`;
}

const springs = Object.fromEntries(
  Object.entries(tokens.springs).map(([name, spec]) => [name, { ...spec, omega: frequency(spec) }]),
);

// --- Dither matrices -------------------------------------------------------

// The classic recursive Bayer construction: each cell of a tile splits into
// four, ordered 0 2 / 3 1.
function bayer(size) {
  if (size === 1) return [0];
  const half = size / 2;
  const smaller = bayer(half);
  const ranks = new Array(size * size);
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      const quadrant = [[0, 2], [3, 1]][y >= half ? 1 : 0][x >= half ? 1 : 0];
      ranks[y * size + x] = 4 * smaller[(y % half) * half + (x % half)] + quadrant;
    }
  }
  return ranks;
}

const matrices = { 2: bayer(2), 4: bayer(4), 8: bayer(8) };

// A clustered-dot screen: cells rank by how near they sit to the middle of a dot, so
// ink grows in round dots on a 45 degree grid, as in print.
function halftone(size) {
  const near = (x, y) => {
    const dot = ([cx, cy]) => {
      const dx = Math.min(Math.abs(x - cx), size - Math.abs(x - cx));
      const dy = Math.min(Math.abs(y - cy), size - Math.abs(y - cy));
      return dx * dx + dy * dy;
    };
    return Math.min(dot([1.5, 1.5]), dot([5.5, 5.5]));
  };
  const cells = [];
  for (let y = 0; y < size; y += 1) for (let x = 0; x < size; x += 1) cells.push({ index: y * size + x, reach: near(x, y) });
  cells.sort((a, b) => a.reach - b.reach || a.index - b.index);
  const ranks = new Array(size * size);
  cells.forEach(({ index }, rank) => (ranks[index] = rank));
  return ranks;
}

const halftoneRanks = halftone(8);

// --- World map -------------------------------------------------------------

const WORLD_WIDTH = 144;
const WORLD_HEIGHT = 72;

function insidePolygon(lon, lat, polygon) {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i, i += 1) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

// One bit per cell, row by row from the north.
const worldBits = new Uint8Array(Math.ceil((WORLD_WIDTH * WORLD_HEIGHT) / 8));
for (let y = 0; y < WORLD_HEIGHT; y += 1) {
  for (let x = 0; x < WORLD_WIDTH; x += 1) {
    const lon = ((x + 0.5) / WORLD_WIDTH) * 360 - 180;
    const lat = 90 - ((y + 0.5) / WORLD_HEIGHT) * 180;
    if (world.polygons.some((polygon) => insidePolygon(lon, lat, polygon))) {
      const bit = y * WORLD_WIDTH + x;
      worldBits[bit >> 3] |= 1 << (bit & 7);
    }
  }
}

// --- Colors ----------------------------------------------------------------

function parseHex(hex) {
  const value = hex.replace('#', '');
  return {
    r: parseInt(value.slice(0, 2), 16),
    g: parseInt(value.slice(2, 4), 16),
    b: parseInt(value.slice(4, 6), 16),
    a: value.length === 8 ? parseInt(value.slice(6), 16) : 255,
  };
}

// OKLCH to sRGB, clamped to the gamut.
function oklchHex(lightness, chroma, hue) {
  const a = chroma * Math.cos((hue * Math.PI) / 180);
  const b = chroma * Math.sin((hue * Math.PI) / 180);
  const l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (lightness - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const channels = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  const encode = (value) => {
    const linear = Math.min(1, Math.max(0, value));
    const gamma = linear <= 0.0031308 ? 12.92 * linear : 1.055 * linear ** (1 / 2.4) - 0.055;
    return Math.round(gamma * 255).toString(16).padStart(2, '0');
  };
  return `#${channels.map(encode).join('')}`.toUpperCase();
}

const palette = (theme) =>
  Object.entries(tokens.palette.hues).map(([name, hue]) => [
    name,
    oklchHex(tokens.palette.lightness[theme], tokens.palette.chroma, hue),
  ]);

const surfaceShadow = (theme, level) => {
  const [y, blur] = tokens.surfaces.shadow[level];
  const { line, shadow } = tokens.themes[theme];
  return y === 0 ? `0 0 0 1px ${line}` : `0 0 0 1px ${line}, 0 ${y}px ${blur}px ${shadow}`;
};

// --- CSS -------------------------------------------------------------------

function themeVariables(theme) {
  const lines = [];
  for (const [name, value] of Object.entries(tokens.themes[theme])) lines.push(`--fd-${kebab(name)}: ${value};`);
  for (const [name, value] of palette(theme)) lines.push(`--fd-${name}: ${value};`);
  tokens.surfaces[theme].forEach((value, level) => {
    lines.push(`--fd-surface-${level}: ${value};`);
    lines.push(`--fd-shadow-${level}: ${surfaceShadow(theme, level)};`);
  });
  lines.push(`color-scheme: ${theme};`);
  return lines.map((line) => `  ${line}`).join('\n');
}

const sizeVariables = (size) =>
  Object.entries(size)
    .map(([name, value]) => `  --fd-${kebab(name)}: ${value}px;`)
    .join('\n');

// A glyph as a box-shadow list on one 2px cell, offset to center it in a box.
function glyphShadow(rows) {
  const cells = [];
  rows.forEach((row, y) => {
    [...row].forEach((mark, x) => {
      if (mark === '#') cells.push(`${x * GLYPH_CELL}px ${y * GLYPH_CELL}px currentColor`);
    });
  });
  return cells.join(', ');
}

const GLYPH_CELL = 2;
const glyphVariables = Object.entries(tokens.glyphs)
  .filter(([name]) => !name.startsWith('$'))
  .flatMap(([name, rows]) => [
    `  --fd-glyph-${kebab(name)}: ${glyphShadow(rows)};`,
    `  --fd-glyph-${kebab(name)}-width: ${rows[0].length * GLYPH_CELL}px;`,
    `  --fd-glyph-${kebab(name)}-height: ${rows.length * GLYPH_CELL}px;`,
  ])
  .join('\n');

const springVariables = Object.entries(springs)
  .map(([name, spring]) => `  --fd-spring-${kebab(name)}: ${Math.round(spring.duration * 1000)}ms ${cssEasing(spring)};`)
  .join('\n');

const stillSprings = Object.keys(springs)
  .map((name) => `    --fd-spring-${kebab(name)}: 0.01ms linear;`)
  .join('\n');

